const CHAR_W = 6; // 5 columns plus 1 of spacing
const CHAR_H = 7;

/**
 * Text as a list of filled rectangles { x0, y0, x1, y1 } (x1/y1 exclusive),
 * top-left at (x, y), each font pixel drawn as scale x scale.
 */
function textRects(text, x, y, scale) {
  const rects = [];
  const chars = String(text).toUpperCase();
  for (let i = 0; i < chars.length; i++) {
    const g = GLYPHS[chars[i]];
    if (!g) continue;
    const cx = x + i * CHAR_W * scale;
    for (let r = 0; r < CHAR_H; r++) {
      // Merge runs of lit pixels in a row into one rectangle.
      let c = 0;
      while (c < 5) {
        if (g[r][c] !== '1') {
          c++;
          continue;
        }
        let end = c;
        while (end < 5 && g[r][end] === '1') end++;
        rects.push({ x0: cx + c * scale, y0: y + r * scale, x1: cx + end * scale, y1: y + (r + 1) * scale });
        c = end;
      }
    }
  }
  return rects;
}

function textWidth(text, scale) {
  return String(text).length * CHAR_W * scale - scale;
}

module.exports = { textRects, textWidth, CHAR_H };
